// Product integration only: import the tool-authored body; never author/install OpenClaw skills.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const read = p => fs.readFileSync(new URL(p, root), 'utf8');
const hash = s => createHash('sha256').update(s).digest('hex');
const manifest = JSON.parse(read('packages/core/src/rescue-knowledge-manifest.json'));
const source = read(manifest.authoring.source);
if (hash(source) !== manifest.authoring.sourceSha256) throw Error('Authoring source revision mismatch: explicit review/import required');
if (source.length >= 10000) throw Error('Keep the authored procedure under 10,000 characters');
if (/\/home\/[a-z]|\/Users\/|qwen3\.8|gpt-5\.6|127\.0\.0\.1:4000/.test(source)) throw Error('Host-specific values do not belong in trusted knowledge');
const sections = new Map([...source.matchAll(/^## ([a-z0-9-]+)\n([\s\S]*?)(?=^## |$(?![\s\S]))/gm)].map(m => [m[1], m[2].trim()]));
if (sections.size !== manifest.entries.length) throw Error('Section/manifest mismatch');
const entries = manifest.entries.map(entry => {
  const body = sections.get(entry.id);
  if (!body) throw Error(`Missing authored section: ${entry.id}`);
  for (const evidence of entry.evidence) {
    if (!/^docs\/rescue-evidence\/[a-z0-9-]+\.json$/.test(evidence.path)) throw Error('Evidence must be a bundled public artifact');
    const content = read(evidence.path);
    if (hash(content) !== evidence.sha256) throw Error(`Evidence revision changed: ${evidence.path}`);
    const original = evidence.original;
    if (!original || !/^acceptance\/[a-z0-9-]+\/(REPORT\.zh-CN\.md|incremental\.diff)$/.test(original.path)
      || !/^[a-f0-9]{64}$/.test(original.sha256)) throw Error('Missing historical evidence provenance');
    // Historical originals remain private. Pin the reviewed public projection,
    // retain the original hash, and never claim this replays raw live acceptance.
    if (original.kind === 'report-excerpts') {
      const projection = JSON.parse(content);
      if (projection.schemaVersion !== 1 || projection.source.path !== original.path
        || projection.source.sha256 !== original.sha256 || !projection.scope
        || !Array.isArray(projection.excerpts) || !projection.excerpts.length
        || projection.excerpts.some(e => !Number.isInteger(e.startLine) || e.startLine < 1
          || !Number.isInteger(e.endLine) || e.endLine < e.startLine || typeof e.text !== 'string' || !e.text)) {
        throw Error('Public excerpt provenance mismatch');
      }
    } else if (original.kind === 'exact-public-patch') {
      const projection = JSON.parse(content);
      if (projection.schemaVersion !== 1 || projection.source.path !== original.path
        || projection.source.sha256 !== original.sha256 || typeof projection.patch !== 'string'
        || hash(projection.patch) !== original.sha256) throw Error('Public patch must preserve original bytes');
    } else throw Error('Unknown public evidence projection');
  }
  const data = { ...entry, steps: body.split(/\n(?=\d+\. )/).map(s => s.replace(/^\d+\. /, '')), body };
  return { ...data, revision: `sha256:${hash(JSON.stringify(data))}` };
});
const pack = { schemaVersion: manifest.schemaVersion, packVersion: manifest.packVersion, authoring: manifest.authoring, entries };
const output = '// Generated by scripts/generate-rescue-knowledge.mjs; edit only reviewed source/manifest.\n' +
  'export const RESCUE_KNOWLEDGE_DATA = ' + JSON.stringify(pack, null, 2) + ' as const;\n';
const dest = new URL('packages/core/src/rescue-knowledge-data.ts', root);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(dest, 'utf8') !== output) throw Error('Generated knowledge is stale');
  console.log(`Knowledge ${pack.packVersion}: ${entries.length} entries; source/evidence/generated hashes verified`);
} else fs.writeFileSync(dest, output);
