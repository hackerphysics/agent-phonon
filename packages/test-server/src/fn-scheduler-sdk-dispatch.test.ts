import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { AdapterRegistry, PhononClient } from "@agent-phonon/core";
import { PhononDevice, PhononServer, type RunResolveInput, type ScheduleTargetInput } from "@agent-phonon/server-sdk";
import { MockAdapter } from "./harness.js";

test("SDK dispatch target and resolution cross the real websocket without branded input casts or a model", async t => {
  const root = mkdtempSync(join(tmpdir(), "phonon-sdk-dispatch-"));
  const server = new PhononServer({ host: "127.0.0.1", authenticate: () => ({ tenantId: "sdk-dispatch" }) });
  const port = await server.listen();
  const ready = new Promise<PhononDevice>(resolve => server.once("device", resolve));
  const registry = new AdapterRegistry();
  const adapter = new MockAdapter({ name: "mock", agentIds: ["mock:default"], models: ["m1"] });
  let models = 0; const create = adapter.createSession.bind(adapter);
  adapter.createSession = async params => { models++; return create(params); };
  registry.register(adapter);
  const client = new PhononClient({ serverUrl: `ws://127.0.0.1:${port}`, deviceId: "sdk-dispatch-device", deviceKey: "isolated-key",
    registry, workspaceRoot: root, trustLocal: true });
  t.after(async () => { await client.close(); await server.close(); rmSync(root, { recursive: true, force: true }); });
  await client.connect(); const device = await ready;
  const info = await device.info() as { capabilities: string[] };
  assert.ok(info.capabilities.includes("schedule_dispatch_v1"));
  const { project } = await device.project.create({ name: "owned", git: false });
  const dispatch = { key: "sdk-automation", revision: 1, contentHash: "a".repeat(64), expiresAt: new Date(Date.now() + 60000).toISOString() };
  const target: ScheduleTargetInput = { runKind: "dispatch", project: String(project.projectId), dispatch };
  const { schedule } = await device.schedule.create({ name: "sdk-dispatch", trigger: { kind: "manual" }, target, consent: { push: "full" } });
  const triggered = await device.schedule.trigger({ scheduleId: schedule.id, input: { event: "untrusted-data" }, clientRequestId: "original-trigger" });
  const pending = await device.schedule.runs.list({ scheduleId: schedule.id, unackedOnly: true, limit: 100 });
  assert.equal(pending.runs.length, 1);
  assert.deepEqual(pending.runs[0]?.dispatch, dispatch);
  assert.deepEqual(pending.runs[0]?.input, { event: "untrusted-data" });
  assert.equal(models, 0);
  const resolve: RunResolveInput = { runId: String(triggered.runId), dispatch, status: "success", resultText: "verified controller outcome", clientRequestId: "original-resolution" };
  const settled = await device.run.resolve(resolve);
  assert.equal(settled.run.status, "success");
  assert.equal((await device.run.get(triggered.runId)).run.resultText, "verified controller outcome");
  await assert.rejects(() => device.run.resolve({ ...resolve, status: "failed" }));
  assert.equal((await device.schedule.runs.list({ scheduleId: schedule.id, unackedOnly: true })).runs.length, 1);
  device.schedule.ack(triggered.runId, { finished: true });
  assert.equal((await device.schedule.runs.list({ scheduleId: schedule.id, unackedOnly: true })).runs.length, 0);
  await device.schedule.update({ scheduleId: schedule.id, consent: { push: "status-only" } });
  const next = await device.schedule.trigger({ scheduleId: schedule.id, input: { private: "never pushed" } });
  const notice = new Promise<{ run: Record<string, unknown> }>(accept => device.once("runFinished", accept));
  await device.run.resolve({ runId: next.runId, dispatch, status: "success" });
  const observed = await notice;
  assert.equal(observed.run.controllerDispatch, true);
  assert.equal(observed.run.dispatch, undefined); assert.equal(observed.run.input, undefined);
  assert.equal((await device.schedule.runs.list({ scheduleId: schedule.id, unackedOnly: true })).runs.length, 1);
  assert.equal(models, 0);
});
