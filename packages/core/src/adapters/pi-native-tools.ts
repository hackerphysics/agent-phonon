import { createHash, randomBytes } from "node:crypto";
import { lstatSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PhononError } from "../rpc.js";
import type { SendOptions } from "../adapter.js";
import { nativeControllerToolNames, selectedNativeControllerTools, verifiedNativeToolChannel } from "../native-tool-channel.js";
import { piHitlStateDir } from "../pi-hitl-extension.js";
import { PI_PEER_CONTEXT_SOURCE } from "./pi-peer-context.js";

export const PI_NATIVE_TOOLS_SOURCE = `// Generated by agent-phonon; capabilities remain in the child environment only.
import {fileURLToPath} from "node:url";
import {request as httpRequest} from "node:http";
import {randomUUID} from "node:crypto";
const allowed = ${JSON.stringify(nativeControllerToolNames)};
const failure = () => new Error("Native Pi tool result is unconfirmed. Effects may have occurred; reconcile the original request identity, never infer approval or repeat with a new request ID.");
${PI_PEER_CONTEXT_SOURCE}
export default async function activate(pi) {
  const environment = process.env;
  const expected=JSON.parse(environment.AGENT_PHONON_PI_NATIVE_TOOL_NAMES||"[]");
  if(!Array.isArray(expected)||new Set(expected).size!==expected.length||expected.some(name=>!allowed.includes(name)))throw failure();
  delete environment.AGENT_PHONON_PI_NATIVE_TOOL_NAMES;
  const peerEnabled = await installPeerContext(pi, environment);
  if(peerEnabled && !expected.length) {
    const nonce = environment.AGENT_PHONON_PI_NATIVE_NONCE;
    if(!/^[a-f0-9]{32}$/.test(nonce || "")) throw failure();
    pi.on("session_start",()=>process.stderr.write("PHONON_PI_NATIVE_TOOLS_ACTIVE_" + nonce + "\\n"));
    process.stderr.write("PHONON_PI_NATIVE_TOOLS_READY_" + nonce + "\\n");
    return;
  }
  const endpoint = new URL(environment.AGENT_PHONON_MCP_URL || "");
  const interaction = new URL(environment.AGENT_PHONON_INTERACTION_URL || "");
  const token = environment.AGENT_PHONON_INTERACTION_TOKEN, nonce = environment.AGENT_PHONON_PI_NATIVE_NONCE;
  if(endpoint.protocol !== "http:" || endpoint.hostname !== "127.0.0.1" || !endpoint.port || endpoint.pathname !== "/mcp" || endpoint.search || endpoint.hash || endpoint.username || endpoint.password
    || interaction.origin !== endpoint.origin || interaction.pathname !== "/interaction" || interaction.search || interaction.hash || interaction.username || interaction.password
    || !/^[A-Za-z0-9_-]{43}$/.test(token || "") || !/^[a-f0-9]{32}$/.test(nonce || "") || typeof pi.getAllTools !== "function" || typeof pi.getActiveTools !== "function" || typeof pi.registerTool !== "function" || typeof pi.on !== "function") throw failure();
  let sequence = 0;
  async function rpc(method, params, signal, timeout) {
    try {
      const id = ++sequence;
      const signals = [AbortSignal.timeout(timeout)]; if(signal) signals.push(signal);
      const value = await new Promise((resolve,reject)=>{
        const req = httpRequest(endpoint,{method:"POST",agent:false,headers:{Authorization:"Bearer " + token,"Content-Type":"application/json",Accept:"application/json, text/event-stream"},signal:AbortSignal.any(signals)},res=>{
          const chunks=[];let size=0;
          res.on("data",chunk=>{size+=chunk.length;if(size>65536){res.destroy();reject(failure());}else chunks.push(chunk);});
          res.on("error",()=>reject(failure()));
          res.on("end",()=>{try{if(res.statusCode!==200)throw failure();resolve(JSON.parse(Buffer.concat(chunks).toString("utf8")));}catch{reject(failure());}});
        });
        req.on("error",()=>reject(failure()));req.end(JSON.stringify({jsonrpc:"2.0",id,method,params}));
      });
      if(value.jsonrpc !== "2.0" || value.id !== id || value.error || !value.result || value.result.isError) throw failure();
      return value.result;
    } catch { throw failure(); }
  }
  await rpc("initialize",{protocolVersion:"2025-03-26",capabilities:{},clientInfo:{name:"phonon-pi-current-turn",version:"1"}},undefined,10000);
  const catalog = await rpc("tools/list",{},undefined,10000);
  if(!expected.length||!Array.isArray(catalog.tools) || catalog.tools.length !== expected.length || new Set(catalog.tools.map(tool=>tool.name)).size !== catalog.tools.length
    || !expected.every(name=>catalog.tools.some(tool=>tool.name===name))
    || catalog.tools.some(tool=>!expected.includes(tool.name) || typeof tool.description !== "string" || !tool.inputSchema || tool.inputSchema.type !== "object")) throw failure();
  const self = fileURLToPath(import.meta.url); let registered = false;
  const stop = () => { process.stderr.write("Native Pi tools unavailable before inference\\n"); process.exit(1); };
  const verify = () => {
    const all = pi.getAllTools(), active = pi.getActiveTools();
    if(!registered || !Array.isArray(all) || !Array.isArray(active) || catalog.tools.some(tool=>{
      const actual = all.find(value=>value.name===tool.name);
      return !actual || actual.sourceInfo?.path !== self || actual.description !== tool.description || JSON.stringify(actual.parameters)!==JSON.stringify(tool.inputSchema) || !active.includes(tool.name);
    })) throw failure();
  };
  pi.on("session_start", () => { try {
    const existing = pi.getAllTools();
    if(!Array.isArray(existing) || existing.some(tool=>allowed.includes(tool.name))) throw failure();
    for(const tool of catalog.tools) pi.registerTool({name:tool.name,label:tool.name,description:tool.description,parameters:tool.inputSchema,
    async execute(_id, params, signal) {
      verify();
      const result = await rpc("tools/call",{name:tool.name,arguments:params},signal,1800000);
      if(!Array.isArray(result.content) || result.content.some(item=>item.type!=="text" || typeof item.text!=="string")) throw failure();
      return {content:result.content,details:{source:"phonon-current-turn"}};
    }});
    registered = true; verify(); process.stderr.write("PHONON_PI_NATIVE_TOOLS_ACTIVE_" + nonce + "\\n");
  } catch { stop(); } });
  pi.on("before_provider_request", () => { try { verify(); } catch { stop(); } });
  process.stderr.write("PHONON_PI_NATIVE_TOOLS_READY_" + nonce + "\\n");
}
`;

/** Invocation-scoped registration, independent from the optional pre-tool HITL gate. */
export function preparePiNativeTools(options: SendOptions): { path: string; acknowledgement: string; nonce: string; names: string[]; cleanup: () => void } | undefined {
  const names=selectedNativeControllerTools(options);
  if (!names.length && !options.peerContext) return undefined;
  try {
    if (names.length) verifiedNativeToolChannel(options.environment ?? {});
    if (options.peerContext) {
      const url = new URL(options.environment?.AGENT_PHONON_PEER_CONTEXT_URL ?? "");
      if (url.protocol !== "http:" || url.hostname !== "127.0.0.1" || !url.port || url.pathname !== "/peer-context"
        || url.username || url.password || url.search || url.hash || !/^[A-Za-z0-9_-]{43}$/.test(options.environment?.AGENT_PHONON_PEER_CONTEXT_TOKEN ?? "")) throw new Error("invalid checkpoint");
    }
  }
  catch { throw new PhononError("errCapabilityUnsupported", "Native Pi tools require a verified current-turn local channel"); }
  const digest = createHash("sha256").update(PI_NATIVE_TOOLS_SOURCE).digest("hex").slice(0, 16);
  const state = piHitlStateDir(); mkdirSync(state, { recursive: true, mode: 0o700 });
  const stat = lstatSync(state);
  if (!stat.isDirectory() || stat.isSymbolicLink() || process.platform !== "win32" && (stat.uid !== process.getuid?.() || (stat.mode & 0o022) !== 0)) throw new PhononError("errCapabilityUnsupported", "Native Pi tool state directory is not trusted");
  const directory = mkdtempSync(join(realpathSync(state), "pi-native-tools-")), path = join(directory, "tools-" + digest + ".mjs");
  try { writeFileSync(path, PI_NATIVE_TOOLS_SOURCE, { mode: 0o600, flag: "wx" }); }
  catch (error) { rmSync(directory, { recursive: true, force: true }); throw error; }
  const nonce = randomBytes(16).toString("hex");
  return { path, nonce, names, acknowledgement: "PHONON_PI_NATIVE_TOOLS_READY_" + nonce, cleanup: () => rmSync(directory, { recursive: true, force: true }) };
}
