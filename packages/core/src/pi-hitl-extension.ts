import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

/**
 * Pi blocking HITL extension (design D38 / §8 HITL).
 *
 * Pi's extension API documents that a `tool_call` handler can block execution and
 * that `event.input` is mutable before the tool runs:
 *
 *   interface ToolCallEventResult { block?: boolean; reason?: string; terminate?: boolean }
 *   pi.on("tool_call", handler)
 *
 * This module carries that extension as source text and materialises it next to
 * the daemon's other runtime state, so the Pi adapter can load it with
 * `pi --extension <path>`. It is shipped inside the core bundle (same approach as
 * rescue-knowledge-data) rather than as a separate npm package: Pi loads plain
 * TypeScript through jiti, so no separate build is required and the extension can
 * never drift from the adapter that loads it.
 *
 * Wire contract (identical to the OpenClaw plugin, see hook-bridge.ts):
 *   POST {bridge}/hook/before_tool_call  { sessionKey, toolName, params }
 *   -> { action: "continue"|"abort"|"inject"|"modify", reason?, patch? }
 *
 * Fail mode: `closed` is the default here. If the bridge is configured but
 * unreachable, dangerous tool calls are blocked rather than silently allowed.
 * The OpenClaw plugin is fail-open; this one is opt-outable via
 * AGENT_PHONON_HITL_FAIL_MODE=open, and the difference is deliberate because an
 * operator who explicitly enabled HITL asked for a gate, not a best-effort hint.
 */

/** Stable path for the materialised extension; content-addressed so edits drop a new file. */
export function piHitlExtensionPath(stateDir: string): string {
  return join(stateDir, "pi", "agent-phonon-hitl", "hitl-extension.ts");
}

export const PI_HITL_EXTENSION_SOURCE = `// Generated by agent-phonon. Do not edit; regenerate by reinstalling the daemon.
// Blocking pre-tool HITL bridge: Pi \`tool_call\` handler -> phonon hook bridge.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

const BRIDGE = process.env.AGENT_PHONON_HITL_BRIDGE;
const TOKEN = process.env.AGENT_PHONON_HITL_TOKEN;
const SESSION = process.env.AGENT_PHONON_HITL_SESSION;
const TIMEOUT_MS = Number(process.env.AGENT_PHONON_HITL_TIMEOUT_MS ?? "120000");
const FAIL_MODE = process.env.AGENT_PHONON_HITL_FAIL_MODE ?? "closed";

// Tools that can change the host or exfiltrate data; these are the ones worth
// gating when the bridge is unreachable and fail-closed is in effect.
const DANGEROUS = /^(bash|powershell|write|edit)$/i;

export default function activate(pi: ExtensionAPI): void {
  if (!BRIDGE) return; // HITL not configured: never load behaviour we cannot enforce.

  pi.on("tool_call", async (event: any) => {
    let reachable = true;
    let decision: any;
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
    try {
      const headers: Record<string, string> = { "content-type": "application/json" };
      if (TOKEN) headers.authorization = \`Bearer \${TOKEN}\`;
      const res = await fetch(\`\${BRIDGE}/hook/before_tool_call\`, {
        method: "POST",
        headers,
        body: JSON.stringify({ sessionKey: SESSION, toolName: event.toolName, params: event.input }),
        signal: controller.signal,
      });
      if (!res.ok) reachable = false;
      else decision = await res.json();
    } catch {
      reachable = false;
    } finally {
      clearTimeout(timer);
    }

    if (!reachable) {
      // Bridge configured but unusable. Do not silently drop the gate on tools
      // that can run commands or rewrite files.
      if (FAIL_MODE === "closed" && DANGEROUS.test(String(event.toolName ?? ""))) {
        return { block: true, reason: "agent-phonon HITL bridge unreachable (fail-closed)" };
      }
      return undefined;
    }

    if (decision?.action === "abort") {
      return { block: true, reason: decision.reason ?? "blocked by agent-phonon HITL" };
    }
    if (decision?.action === "modify" && decision.patch && event.input && typeof event.input === "object") {
      Object.assign(event.input, decision.patch);
    }
    return undefined;
  });
}
`;

/** Where the adapter should keep generated bridge assets. */
export function piHitlStateDir(): string {
  return join(process.env.PHONON_STATE_DIR ?? join(homedir(), ".agent-phonon"));
}

/**
 * Write the extension if its content changed, and return its path.
 * Idempotent: same content -> same path -> no rewrite, so a long-running daemon
 * does not touch the file on every turn.
 */
export function materializePiHitlExtension(stateDir = piHitlStateDir()): string {
  const path = piHitlExtensionPath(stateDir);
  const source = PI_HITL_EXTENSION_SOURCE;
  let current: string | undefined;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    current = undefined;
  }
  if (current !== source) {
    mkdirSync(join(path, ".."), { recursive: true, mode: 0o700 });
    writeFileSync(path, source, { mode: 0o600 });
  }
  return path;
}

/** Content hash of the shipped extension, so tests can detect drift. */
export function piHitlExtensionHash(): string {
  return createHash("sha256").update(PI_HITL_EXTENSION_SOURCE).digest("hex").slice(0, 16);
}